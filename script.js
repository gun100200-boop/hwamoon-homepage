document.addEventListener('DOMContentLoaded', () => {
    const reservationForm = document.getElementById('reservation-form');
    const timeSelect = document.getElementById('time');
    const langSelector = document.getElementById('lang-selector');
    const reviewMarquee = document.getElementById('review-marquee');
    const dateInput = document.getElementById('date');
    
    let currentLang = 'en';
    let fp = null;

    if (dateInput) {
        fp = flatpickr(dateInput, {
            dateFormat: "Y-m-d",
            minDate: "today",
            locale: "en",
            disableMobile: "true"
        });
    }

    const updateLanguage = (lang) => {
        currentLang = lang;
        document.querySelectorAll('[data-i18n]').forEach(el => {
            const key = el.getAttribute('data-i18n');
            if (translations[lang][key]) el.textContent = translations[lang][key];
        });

        document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
            const key = el.getAttribute('data-i18n-placeholder');
            if (translations[lang][key]) el.placeholder = translations[lang][key];
        });

        if (fp) {
            let fpLocale = lang;
            if (lang === 'zh-cn') fpLocale = 'zh';
            if (lang === 'zh-tw') fpLocale = 'zh_tw';
            fp.set("locale", fpLocale);
        }

        if (reviewMarquee) {
            const reviewList = translations[lang].reviews;
            reviewMarquee.innerHTML = [...reviewList, ...reviewList].map(text => 
                `<div class="review-card">${text}</div>`
            ).join('');
        }

        const timePlaceholder = timeSelect.querySelector('option[value=""]');
        if (timePlaceholder) timePlaceholder.textContent = translations[lang].option_select_time;
    };

    if (langSelector) langSelector.addEventListener('change', (e) => updateLanguage(e.target.value));

    if (timeSelect) {
        const startHour = 11, startMinute = 30, endHour = 22;
        for (let h = startHour; h <= endHour; h++) {
            for (let m = 0; m < 60; m += 15) {
                if (h === 11 && m < 30) continue;
                if (h === 22 && m > 0) break;
                const timeStr = `${h.toString().padStart(2, '0')}:${m.toString().padStart(2, '0')}`;
                const option = document.createElement('option');
                option.value = timeStr;
                option.textContent = timeStr;
                timeSelect.appendChild(option);
            }
        }
    }

    if (reservationForm) {
        reservationForm.addEventListener('submit', (e) => {
            e.preventDefault();
            const name = document.getElementById('name').value;
            const dVal = document.getElementById('date').value;
            const tVal = document.getElementById('time').value;
            const pax = document.getElementById('pax').value;
            const requests = document.getElementById('requests').value;

            if (!dVal || !tVal) return;

            const selectedDateTime = new Date(`${dVal}T${tVal}`);
            if (selectedDateTime < new Date()) {
                alert(translations[currentLang].alert_past_time);
                return;
            }

            const phoneNumber = "6281999777283"; 
            const t = translations[currentLang];
            const dateObj = new Date(dVal);
            const localizedDate = new Intl.DateTimeFormat(currentLang === 'zh-cn' ? 'zh-Hans-CN' : currentLang === 'zh-tw' ? 'zh-Hant-TW' : currentLang, {
                year: 'numeric', month: 'long', day: 'numeric'
            }).format(dateObj);

            let message = `${t.msg_header}\n\n${t.msg_name}: ${name}\n${t.msg_date}: ${localizedDate}\n${t.msg_time}: ${tVal}\n${t.msg_pax}: ${pax}`;
            
            if (requests.trim() !== "") {
                message += `\n${t.msg_requests}: ${requests}`;
            }
            
            message += `\n\n${t.msg_footer}`;
            window.open(`https://wa.me/${phoneNumber}?text=${encodeURIComponent(message)}`, '_blank');
        });
    }

    const observer = new IntersectionObserver((entries) => {
        entries.forEach(entry => {
            if (entry.isIntersecting) {
                entry.target.classList.add('animate-up');
                observer.unobserve(entry.target);
            }
        });
    }, { threshold: 0.1 });

    document.querySelectorAll('.section-title, .menu-item').forEach(el => {
        el.style.opacity = '0';
        el.style.transform = 'translateY(30px)';
        el.style.transition = 'all 0.8s ease-out';
        observer.observe(el);
    });

    updateLanguage('en');
});

document.addEventListener('scroll', () => {
    const header = document.querySelector('header');
    if (header) {
        if (window.scrollY > 50) {
            header.style.padding = '0.5rem 5%';
            header.style.backgroundColor = 'rgba(26, 26, 26, 0.98)';
        } else {
            header.style.padding = '1rem 5%';
            header.style.backgroundColor = 'rgba(26, 26, 26, 0.95)';
        }
    }
});
